/** Formats scaled quantities with friendly fractions (½, ¼, ¾). */
function formatQty(n) {
  const whole = Math.floor(n);
  const frac = Math.round((n - whole) * 100) / 100;
  const sym = frac === 0 ? '' : frac === 0.5 ? '½' : frac === 0.25 ? '¼' : frac === 0.75 ? '¾' : null;
  if (sym === null) return String(Math.round(n * 10) / 10);
  return (whole ? String(whole) : '') + sym;
}
